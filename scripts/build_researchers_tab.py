"""Build assets/researchers.js: the Researchers tab of the monitor.

Takes the standalone map page (experts/site/index.html) and turns it into a
script that renders the same map inside the monitor, in a shadow DOM so its
styles cannot clash with the monitor's. Data is fetched from experts/site/
only when the tab is first opened.

Run after changing experts/site/index.html:  python3 scripts/build_researchers_tab.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "experts", "site", "index.html"), encoding="utf-8").read()

css = re.search(r"<style>(.*?)</style>", src, re.S).group(1)
html = re.search(r"</style>\s*(.*?)\s*<script>", src, re.S).group(1)
js = re.search(r"<script>\s*\(function \(\) \{\s*(.*?)\}\)\(\);\s*</script>", src, re.S).group(1)

# CSS: page-level selectors become shadow-host selectors
css = css.replace(':root:not([data-theme="light"])', ":host").replace(':root[data-theme="dark"]', ':host([data-theme="dark"])').replace(":root", ":host")
css = re.sub(r"(^|\n)body \{", r"\1:host { display: block;", css)
css += "\n:host { background: transparent; }\n.wrap { padding-left: 0; padding-right: 0; max-width: none; }\n.sr-only { position: absolute; width: 1px; height: 1px; overflow: hidden; clip: rect(0 0 0 0); white-space: nowrap; }\n"

# JS: query inside the shadow root; fetch from experts/site/
js = js.replace('const $ = (s) => document.querySelector(s);', 'const $ = (s) => R.querySelector(s);')
js = js.replace('fetch("catalogue.json")', 'fetch(BASE + "catalogue.json")').replace('fetch("chile_outline.json")', 'fetch(BASE + "chile_outline.json")')
assert "R.querySelector" in js and "BASE +" in js

out = f"""/* Generated by scripts/build_researchers_tab.py from experts/site/index.html. Do not edit by hand. */
(function () {{
  "use strict";
  const BASE = "experts/site/";
  const CSS = {json.dumps(css, ensure_ascii=False)};
  const HTML = {json.dumps(html, ensure_ascii=False)};
  let started = false;
  window.PWM_initResearchers = function (host) {{
    if (started || !host) return;
    started = true;
    const R = host.attachShadow ? host.attachShadow({{ mode: "open" }}) : host;
    R.innerHTML = "<style>" + CSS + "</style>" + HTML;
{js}
  }};
}})();
"""
open(os.path.join(ROOT, "assets", "researchers.js"), "w", encoding="utf-8").write(out)
print("ok assets/researchers.js", len(out), "bytes")
